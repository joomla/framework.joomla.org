import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import autoprefixer from 'autoprefixer';
import purgeCSSPlugin from '@fullhuman/postcss-purgecss';
import { defineConfig } from 'vite';

const rootDir = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(rootDir, 'www/media');

/**
 * Prebuilt vendor files which are copied to the media directory as is
 */
const copiedFiles = {
    'css/bootstrap.css': 'node_modules/bootstrap/dist/css/bootstrap.css',
    'css/bootstrap.css.map': 'node_modules/bootstrap/dist/css/bootstrap.css.map',
    'css/bootstrap.min.css': 'node_modules/bootstrap/dist/css/bootstrap.min.css',
    'css/bootstrap.min.css.map': 'node_modules/bootstrap/dist/css/bootstrap.min.css.map',
    'js/bootstrap.bundle.js': 'node_modules/bootstrap/dist/js/bootstrap.bundle.js',
    'js/bootstrap.bundle.js.map': 'node_modules/bootstrap/dist/js/bootstrap.bundle.js.map',
};

/**
 * Files which are referenced from the templates and need a versioned URL in the manifest
 */
const versionedFiles = [
    'js/template.js',
    'css/template.css',
    'css/code.css',
    ...Object.keys(copiedFiles).filter((file) => !file.endsWith('.map')),
];

/**
 * Remove unused selectors from the template stylesheet only, the other stylesheets are used for content which isn't part of
 * the templates (e.g. the rendered documentation)
 */
const purgeTemplateCss = () => {
    // The extractor and safelist match the defaults of laravel-mix-purgecss, which was used before
    const purgeCss = purgeCSSPlugin({
        content: ['templates/**/*.twig', 'src/**/*.php', 'assets/js/**/*.js'],
        defaultExtractor: (content) => content.match(/[\w-/.:]+(?<!:)/g) || [],
        safelist: {
            // Classes which are toggled by JavaScript at runtime
            greedy: [/-active$/, /-enter$/, /-leave-to$/, /show$/],
        },
    });

    return {
        postcssPlugin: 'purge-template-css',
        OnceExit(root, helpers) {
            const file = (root.source?.input.file ?? '').replace(/\\/g, '/');

            if (file.endsWith('/assets/scss/template.scss')) {
                return purgeCss.OnceExit(root, helpers);
            }
        },
    };
};
purgeTemplateCss.postcss = true;

/**
 * Copies the vendor files and writes the manifest used by the application to build versioned asset URLs
 *
 * The manifest maps each file to its URL with a content hash as cache buster (i.e. "/css/template.css": "/css/template.css?id=...").
 */
const mediaManifest = () => ({
    name: 'media-manifest',
    apply: 'build',
    buildStart() {
        // The font files are named by content hash, remove the files of previous builds
        rmSync(resolve(outDir, 'fonts'), { recursive: true, force: true });
    },
    closeBundle() {
        for (const [target, source] of Object.entries(copiedFiles)) {
            mkdirSync(dirname(resolve(outDir, target)), { recursive: true });
            copyFileSync(resolve(rootDir, source), resolve(outDir, target));
        }

        const manifest = {};

        for (const file of versionedFiles) {
            const hash = createHash('md5').update(readFileSync(resolve(outDir, file))).digest('hex');
            manifest[`/${file}`] = `/${file}?id=${hash}`;
        }

        writeFileSync(resolve(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 4)}\n`);
    },
});

export default defineConfig({
    // Assets referenced from the stylesheets (fonts, images) are resolved relative to the stylesheet
    base: './',
    publicDir: false,
    css: {
        postcss: {
            plugins: [autoprefixer(), purgeTemplateCss()],
        },
        preprocessorOptions: {
            scss: {
                // Bootstrap and Font Awesome still use the deprecated Sass @import rules and functions
                quietDeps: true,
                silenceDeprecations: ['import', 'global-builtin', 'color-functions', 'if-function'],
            },
        },
    },
    build: {
        outDir,
        // The media directory also contains files which aren't generated by this build
        emptyOutDir: false,
        sourcemap: true,
        assetsInlineLimit: 0,
        rollupOptions: {
            input: {
                'js/template': resolve(rootDir, 'assets/js/template.js'),
                'css/template': resolve(rootDir, 'assets/scss/template.scss'),
                'css/code': resolve(rootDir, 'assets/scss/code.scss'),
            },
            output: {
                entryFileNames: '[name].js',
                chunkFileNames: 'js/[name].js',
                assetFileNames: (assetInfo) => {
                    const name = assetInfo.names?.[0] ?? '';

                    if (/\.css$/.test(name)) {
                        return '[name][extname]';
                    }

                    if (/\.(woff2?|ttf|otf|eot)$/.test(name)) {
                        return 'fonts/[name]-[hash][extname]';
                    }

                    return 'images/[name][extname]';
                },
            },
        },
    },
    plugins: [mediaManifest()],
    experimental: {
        // Reference assets relative to the file using them, the generated files are placed in subdirectories of the media directory
        renderBuiltUrl(filename, { hostId, hostType }) {
            if (hostType === 'css') {
                return posix.relative(posix.dirname(hostId), filename);
            }

            return { relative: true };
        },
    },
});
